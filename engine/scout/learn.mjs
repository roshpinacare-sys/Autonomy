/** our-architecture interest map: pattern → target organs */
export const INTEREST_MAP = [
  { re: /\b(three\.?js|webgl|webgpu|3d|mixamo|rig|retarget|animation|mocap|motion|glb|gltf|avatar)\b/i, organs: ['office3d-world', 'world-evolver'], domain: '3d/animation' },
  { re: /\b(steem|blurt|hive|blockchain|vests|sp|delegation|rpc)\b/i, organs: ['fleet-posting', 'wallet-verify'], domain: 'chain' },
  { re: /\b(supply[- ]chain|malware|scanner|vulnerab|secrets?[- ]scan|sast|gitleaks)\b/i, organs: ['leak-scan', 'scout-vet', 'pub-scrub'], domain: 'security' },
  { re: /\b(agent|autonom|orchestr|swarm|multi[- ]agent|scheduler|cron|workflow)\b/i, organs: ['chainbus', 'self-heal', 'sovereign-tick'], domain: 'autonomy' },
  { re: /\b(llm|inference|prompt|rag|embedding|vector|nim|ollama|openai)\b/i, organs: ['brain (L3, unfired)', 'world-evolver-llm'], domain: 'ai' },
  { re: /\b(wallet|dex|swap|liquidity|amm|token|defi)\b/i, organs: ['saos-dex', 'profit-oracle'], domain: 'defi' },
  { re: /\b(dashboard|visuali[sz]|chart|monitor|observab|status[- ]page)\b/i, organs: ['truth.html', 'office3d-truthwall'], domain: 'observability' },
];

/** compose one knowledge entry from a vet receipt (pure) */
export function lessonFromVet(v) {
  if (!v || typeof v !== 'object' || !v.owner || !v.repo) return null;
  if (v.verdict === 'BLOCKED') {
    return {
      id: `scout-${v.owner}-${v.repo}`.toLowerCase().replace(/[^a-z0-9-]/g, '-'),
      at: new Date().toISOString(),
      repo: `${v.owner}/${v.repo}`,
      verdict: v.verdict,
      status: 'QUARANTINED (never studied — signal corpus hit)',
      reason: v.reason ?? null,
      signals: v.signals ?? [],
      lesson: null,
      cleanRoom: null,
    };
  }
  // GONE / UNREACHABLE are not knowledge — they were never repos or never answered
  if (v.verdict !== 'SAFE_TO_STUDY' && v.verdict !== 'STUDY_WITH_CARE') return null;
  const hay = `${v.repo} ${(v.meta?.description ?? '')} ${(v.meta?.topics ?? []).join(' ')} ${(v.ctx ?? '')}`;
  const matches = INTEREST_MAP.filter((m) => m.re.test(hay));
  const organs = [...new Set(matches.flatMap((m) => m.organs))].slice(0, 6);
  const domains = [...new Set(matches.map((m) => m.domain))].slice(0, 4);
  const topics = (v.meta?.topics ?? []).slice(0, 6);
  const ageDays = v.meta?.createdAt ? Math.floor((Date.now() - Date.parse(v.meta.createdAt)) / 86400000) : null;
  const lesson = {
    summary: (v.meta?.description || v.ctx || '(no description)').slice(0, 220),
    domains,
    topics,
    stars: v.meta?.stars ?? null,
    license: v.meta?.license ?? null,
    ageDays,
    activityDays: v.meta?.pushedAt ? Math.floor((Date.now() - Date.parse(v.meta.pushedAt)) / 86400000) : null,
    appliesTo: organs,
  };
  return {
    id: `scout-${v.owner}-${v.repo}`.toLowerCase().replace(/[^a-z0-9-]/g, '-'),
    at: new Date().toISOString(),
    repo: `${v.owner}/${v.repo}`,
    verdict: v.verdict,
    status: v.verdict === 'SAFE_TO_STUDY' ? 'OPEN FOR STUDY (read-only)' : 'OPEN FOR STUDY (warn-flagged)',
    reason: v.reason,
    signals: v.signals ?? [],
    lesson,
    // clean-room law embedded in every entry — cannot be forgotten
    cleanRoom: 'ORIGINAL IMPLEMENTATION ONLY: never copy code verbatim; study the approach, re-implement from scratch in our repos, respect the license, record attribution here. Integration = proposal → architecture review → original code.',
  };
}

/** render INDEX.md from entries (pure) */
export function renderIndex(entries, run) {
  const lines = [
    '# Scout Knowledge Index — יד-הצייד',
    '',
    `> auto-generated by engine/scout.mjs — last run ${run?.at ?? 'n/a'} · sources fetched: ${run?.sourcesFetched ?? 0} · candidates vetted: ${run?.vetted ?? 0}`,
    '',
    'Laws: knowledge/LEARNING.md (never execute foreign code · clean-room originals · BLOCKED = quarantined by name).',
    '',
    '| repo | verdict | domains | applies to | license |',
    '|---|---|---|---|---|',
  ];
  for (const e of entries.slice(-80).reverse()) {
    if (!e.lesson) { lines.push(`| ${e.repo} | **${e.verdict}** | — | — | — |`); continue; }
    lines.push(`| ${e.repo} | ${e.verdict} | ${(e.lesson.domains || []).join(', ') || '—'} | ${(e.lesson.appliesTo || []).join(', ') || '—'} | ${e.lesson.license ?? '—'} |`);
  }
  lines.push('', '_Every entry carries the clean-room clause. Proposals become original code in our repos or nothing at all._');
  return lines.join('\n') + '\n';
}

/* ── selftest: zero network ──────────────────────────────────────────────── */
export function selftest() {
  const safe = lessonFromVet({ owner: 'MaxLiu22', repo: 'Motion2MixamoRig', verdict: 'SAFE_TO_STUDY', reason: 'clean', signals: [], ctx: 'motion retargeting mixamo rig', meta: { stars: 12, license: 'MIT', description: 'Motion to Mixamo rig retargeting pipeline', topics: ['animation', 'mixamo'], createdAt: '2025-06-01T00:00:00Z', pushedAt: new Date().toISOString() } });
  if (!safe || safe.verdict !== 'SAFE_TO_STUDY') throw new Error('safe entry missing');
  if (!safe.lesson.appliesTo.includes('office3d-world')) throw new Error(`interest map missed: ${JSON.stringify(safe.lesson.appliesTo)}`);
  if (!/ORIGINAL IMPLEMENTATION ONLY/.test(safe.cleanRoom)) throw new Error('clean-room clause missing');
  const blocked = lessonFromVet({ owner: 'evil', repo: 'stealer-tool', verdict: 'BLOCKED', reason: 'critical-signal:cred.env-sweep', signals: [{ id: 'cred.env-sweep', severity: 'critical' }] });
  if (blocked.lesson !== null) throw new Error('BLOCKED must carry no lesson');
  if (blocked.status !== 'QUARANTINED (never studied — signal corpus hit)') throw new Error('quarantine wording');
  if (lessonFromVet(null) !== null || lessonFromVet({}) !== null) throw new Error('malformed input must null');
  const idx = renderIndex([safe, blocked], { at: '2026-10-18T00:00:00Z', sourcesFetched: 1, vetted: 2 });
  if (!idx.includes('| evil/stealer-tool | **BLOCKED** |')) throw new Error('index quarantine row');
  if (!idx.includes('| MaxLiu22/Motion2MixamoRig | SAFE_TO_STUDY |')) throw new Error('index study row');
  console.log('[scout/learn] selftest: PASS (interest-map, quarantine-no-lesson, malformed-null, clean-room clause, index render)');
  return 0;
}

const isMain = process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href;
if (isMain) process.exit(selftest());
